    <script>
    // Smart Header Logic
    let lastScrollTop = 0;
    const header = document.querySelector('header');
    
    window.addEventListener('scroll', function() {
        let scrollTop = window.pageYOffset || document.documentElement.scrollTop;
        
        if (scrollTop > lastScrollTop && scrollTop > 150) {
            // Cuộn xuống - Ẩn header
            header.classList.add('header-hidden');
            header.classList.remove('header-show');
        } else {
            // Cuộn lên - Hiện header
            header.classList.remove('header-hidden');
            header.classList.add('header-show');
        }
        
        if (scrollTop <= 50) {
            header.classList.remove('header-show');
            header.style.boxShadow = 'none';
        }
        
        lastScrollTop = scrollTop;
    }, { passive: true });

    let cartPopupTimeout;
    function showCartPopup() {
        const popup = document.getElementById('cart-success-popup');
        if(!popup) return;
        popup.classList.remove('invisible');
        popup.classList.add('active');
        
        // Tự động đóng sau 3 giây
        clearTimeout(cartPopupTimeout);
        cartPopupTimeout = setTimeout(closeCartPopup, 3000);
    }
    function closeCartPopup() {
        const popup = document.getElementById('cart-success-popup');
        if(!popup) return;
        popup.classList.remove('active');
        setTimeout(() => {
            if(!popup.classList.contains('active')) popup.classList.add('invisible');
        }, 500);
    }
    jQuery(function($) {
        // Hàm cập nhật fragments thủ công để tăng tốc (không phụ thuộc vào script mặc định của Woo)
        function applyFragments(fragments) {
            if (fragments) {
                $.each(fragments, function(selector, html) {
                    $(selector).replaceWith(html);
                });
                $(document.body).trigger('wc_fragments_refreshed');
            }
        }

        // Lắng nghe sự kiện thêm vào giỏ hàng thành công của WooCommerce
        $(document.body).on('added_to_cart', function(event, fragments) {
            showCartPopup();
            applyFragments(fragments);
        });

        // Xử lý tăng giảm số lượng AJAX
        $(document).on('click', '.quantity-btn', function(e) {
            e.preventDefault();
            var btn = $(this);
            var key = btn.data('key');
            var currentQty = parseInt(btn.data('current'));
            var newQty = btn.hasClass('plus') ? currentQty + 1 : currentQty - 1;
            
            if (newQty < 1) return;
            
            updateCart(key, newQty);
        });

        // Xử lý xóa sản phẩm AJAX
        $(document).on('click', '.remove-cart-item', function(e) {
            e.preventDefault();
            var key = $(this).data('key');
            if (confirm('Bạn muốn xóa sản phẩm này khỏi giỏ hàng?')) {
                removeCartItem(key);
            }
        });

        function updateCart(key, qty) {
            $('body').trigger('adding_to_cart');
            $.ajax({
                url: '<?php echo admin_url('admin-ajax.php'); ?>',
                type: 'POST',
                data: {
                    action: 'update_cart_quantity',
                    cart_item_key: key,
                    quantity: qty
                },
                success: function(response) {
                    // response lúc này đã bao gồm fragments từ WC_AJAX::get_refreshed_fragments()
                    applyFragments(response.fragments || response);
                }
            });
        }

        function removeCartItem(key) {
            $('body').trigger('adding_to_cart');
            $.ajax({
                url: '<?php echo admin_url('admin-ajax.php'); ?>',
                type: 'POST',
                data: {
                    action: 'remove_cart_item',
                    cart_item_key: key
                },
                success: function(response) {
                    applyFragments(response.fragments || response);
                }
            });
        }
    });
